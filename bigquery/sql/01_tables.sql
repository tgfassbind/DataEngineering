-- Tables and key functions of the warehouse (dataset core) and the data mart
-- (dataset mart). The datasets themselves are created by Terraform.
--
-- Run once at setup, and again after a change (idempotent: CREATE ... IF NOT
-- EXISTS / CREATE OR REPLACE FUNCTION). Like the local db/init scripts,
-- IF NOT EXISTS does NOT change an existing table: schema changes need a
-- migration or dropping the table.
--
-- BigQuery does not enforce PRIMARY KEY / FOREIGN KEY. They are declared
-- (NOT ENFORCED) to document the model and help the query optimiser; the
-- load script and the data-quality checks verify them.

-- ---------------------------------------------------------------------------
-- Surrogate keys: defined exactly once, used by the dimension MERGEs and the
-- fact load. Deterministic hashes of the natural key, so reruns and backfills
-- always produce the same key (BigQuery has no sequences).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION core.stop_key(bpuic INT64) AS (
  FARM_FINGERPRINT(CAST(bpuic AS STRING))
);

CREATE OR REPLACE FUNCTION core.line_key(linien_text STRING, betreiber_abk STRING) AS (
  FARM_FINGERPRINT(CONCAT(linien_text, '|', betreiber_abk))
);

-- ---------------------------------------------------------------------------
-- The load tables core.stg_stop_event and core.stg_run_scope are NOT created
-- here. Kestra loads them from processed/<day>_stop_events.parquet and
-- processed/<day>_run_scope.parquet (LoadFromGcs, WRITE_TRUNCATE). An overwrite
-- load replaces the table schema with the schema of the Parquet file, so the
-- file (transform/app/output.py) is the one definition of their columns.
-- Planned times arrive as text 'YYYY-MM-DD HH:MM:SS' and are cast to DATETIME
-- in 10_load_core.sql.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Dimensions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core.dim_stop (
  stop_key           INT64      NOT NULL OPTIONS (description = 'Surrogate key, core.stop_key(bpuic).'),
  bpuic              INT64      NOT NULL OPTIONS (description = 'Natural key (BPUIC).'),
  haltestellen_name  STRING              OPTIONS (description = 'Current stop name (SCD type 1).'),
  source_day         DATE       NOT NULL OPTIONS (description = 'Operating day the attributes were taken from.'),
  updated_at         TIMESTAMP  NOT NULL OPTIONS (description = 'Last insert or change.'),
  PRIMARY KEY (stop_key) NOT ENFORCED
)
OPTIONS (description = 'One row per stop. SCD type 1; an older day never overwrites newer attributes.');

CREATE TABLE IF NOT EXISTS core.dim_line (
  line_key             INT64      NOT NULL OPTIONS (description = 'Surrogate key, core.line_key(linien_text, betreiber_abk).'),
  linien_text          STRING     NOT NULL OPTIONS (description = 'Line, e.g. S1. Only unique together with betreiber_abk.'),
  betreiber_abk        STRING     NOT NULL OPTIONS (description = 'Operator abbreviation, e.g. SBB.'),
  betreiber_name       STRING              OPTIONS (description = 'Operator name.'),
  verkehrsmittel_text  STRING              OPTIONS (description = 'Means of transport, e.g. S, IR.'),
  produkt_id           STRING              OPTIONS (description = 'Product, e.g. Zug.'),
  source_day           DATE       NOT NULL OPTIONS (description = 'Operating day the attributes were taken from.'),
  updated_at           TIMESTAMP  NOT NULL OPTIONS (description = 'Last insert or change.'),
  PRIMARY KEY (line_key) NOT ENFORCED
)
OPTIONS (description = 'One row per line of the data product, as defined in transform/config/lines.yml. SCD type 1.');

CREATE TABLE IF NOT EXISTS core.dim_date (
  date          DATE    NOT NULL OPTIONS (description = 'Key.'),
  iso_weekday   INT64   NOT NULL OPTIONS (description = '1 = Monday .. 7 = Sunday.'),
  weekday_name  STRING  NOT NULL,
  is_weekend    BOOL    NOT NULL,
  iso_week      INT64   NOT NULL,
  month         INT64   NOT NULL,
  year          INT64   NOT NULL,
  PRIMARY KEY (date) NOT ENFORCED
)
OPTIONS (description = 'One row per calendar day. Generated by 02_seed_calendar.sql.');

CREATE TABLE IF NOT EXISTS core.dim_time_slot (
  slot_hour  INT64   NOT NULL OPTIONS (description = 'Key, hour 0..23.'),
  label      STRING  NOT NULL OPTIONS (description = 'e.g. 07:00-07:59.'),
  PRIMARY KEY (slot_hour) NOT ENFORCED
)
OPTIONS (description = 'One row per hour of the day. Generated by 02_seed_calendar.sql.');

-- ---------------------------------------------------------------------------
-- Fact
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core.fact_stop_event (
  betriebstag         DATE       NOT NULL OPTIONS (description = 'Operating day; key to dim_date; partition column.'),
  fahrt_bezeichner    STRING     NOT NULL OPTIONS (description = 'Trip id, unique within an operating day (degenerate dimension).'),
  stop_key            INT64      NOT NULL OPTIONS (description = 'Key to dim_stop.'),
  line_key            INT64      NOT NULL OPTIONS (description = 'Key to dim_line.'),
  stop_sequence       INT64      NOT NULL OPTIONS (description = '1-based, gap-free position of the stop within the trip.'),
  sched_arr           DATETIME            OPTIONS (description = 'Planned arrival, Swiss local time; NULL at the first stop.'),
  sched_dep           DATETIME            OPTIONS (description = 'Planned departure, Swiss local time; NULL at the last stop.'),
  arr_slot_hour       INT64               OPTIONS (description = 'Hour of sched_arr; key to dim_time_slot (role: arrival).'),
  dep_slot_hour       INT64               OPTIONS (description = 'Hour of sched_dep; key to dim_time_slot (role: departure).'),
  arr_delay_s         INT64               OPTIONS (description = 'Measure: arrival delay in seconds, negative = early, NULL = no valid measurement.'),
  dep_delay_s         INT64               OPTIONS (description = 'Measure: departure delay in seconds, negative = early, NULL = no valid measurement.'),
  is_additional_trip  BOOL       NOT NULL OPTIONS (description = 'Trip not in the regular timetable (ZUSATZFAHRT_TF).'),
  loaded_at           TIMESTAMP  NOT NULL OPTIONS (description = 'Time the operating day was last loaded.'),
  PRIMARY KEY (betriebstag, fahrt_bezeichner, stop_key) NOT ENFORCED,
  FOREIGN KEY (stop_key)      REFERENCES core.dim_stop (stop_key)       NOT ENFORCED,
  FOREIGN KEY (line_key)      REFERENCES core.dim_line (line_key)       NOT ENFORCED,
  FOREIGN KEY (betriebstag)   REFERENCES core.dim_date (date)           NOT ENFORCED,
  FOREIGN KEY (arr_slot_hour) REFERENCES core.dim_time_slot (slot_hour) NOT ENFORCED,
  FOREIGN KEY (dep_slot_hour) REFERENCES core.dim_time_slot (slot_hour) NOT ENFORCED
)
PARTITION BY betriebstag
CLUSTER BY line_key, stop_key
OPTIONS (description = 'Grain: one served stop of one trip on one operating day.');

-- ---------------------------------------------------------------------------
-- Data mart
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mart.mart_od_delay_by_slot (
  line_key              INT64    NOT NULL,
  linien_text           STRING   NOT NULL,
  betreiber_abk         STRING   NOT NULL,
  from_stop_key         INT64    NOT NULL OPTIONS (description = 'Origin stop (role of dim_stop).'),
  from_stop             STRING            OPTIONS (description = 'Origin stop name, copied from dim_stop at refresh.'),
  to_stop_key           INT64    NOT NULL OPTIONS (description = 'Destination stop (role of dim_stop), any later stop of the same trip.'),
  to_stop               STRING            OPTIONS (description = 'Destination stop name, copied from dim_stop at refresh.'),
  weekday               INT64    NOT NULL OPTIONS (description = 'ISO weekday (1 = Monday) of the planned departure at the origin.'),
  slot_hour             INT64    NOT NULL OPTIONS (description = 'Hour 0..23 of the planned departure at the origin.'),
  median_dep_delay_min  NUMERIC           OPTIONS (description = 'Median departure delay at the origin, minutes, rounded to 0.1. NULL exactly when n_dep_obs = 0.'),
  median_arr_delay_min  NUMERIC           OPTIONS (description = 'Median arrival delay at the destination, minutes, rounded to 0.1. NULL exactly when n_arr_obs = 0.'),
  n_dep_obs             INT64    NOT NULL OPTIONS (description = 'Number of departure measurements behind the median.'),
  n_arr_obs             INT64    NOT NULL OPTIONS (description = 'Number of arrival measurements behind the median.'),
  PRIMARY KEY (line_key, from_stop_key, to_stop_key, weekday, slot_hour) NOT ENFORCED
)
CLUSTER BY linien_text, from_stop, to_stop
OPTIONS (description = 'Data product: median delay per line, origin-destination pair, ISO weekday and one-hour slot. Recomputed in full by 20_refresh_mart.sql.');
